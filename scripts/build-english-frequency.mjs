#!/usr/bin/env node
// Regenerates src/data/englishFrequency.js — the high-frequency English word list
// used as the BASE "known word" set for the reader's dense-page easing on English
// (0510 ESL) docs. See src/lib/englishKnownWords.js and unknownDensity.js.
//
// Source: first20hours/google-10000-english · google-10000-english-no-swears.txt
// (the 10,000 most common English words by frequency, derived from the Google Web
// Trillion Word Corpus; code MIT, data permitted for educational/personal use —
// see public/CREDITS.txt). We take the TOP-N by frequency rank, keep only
// alphabetic words ≥ 2 chars (drops stray numerics / 1-char tokens), lowercase,
// dedupe (rank order preserved), and emit a newline-delimited string (smallest
// gzip footprint). N=2000 covers ~80-85% of running text — high enough that
// normal IGCSE-level English stays under the 40%-unknown nudge threshold, while
// genuinely hard/academic text still crosses it.
//
// Network is needed only to REGENERATE (a maintainer task) — never at app
// build/runtime; the generated asset is committed and lazy-imported.
//
// Usage:
//   node scripts/build-english-frequency.mjs                  # fetch the pinned URL
//   node scripts/build-english-frequency.mjs /path/list.txt   # use a local file
//   node scripts/build-english-frequency.mjs --top 2500       # override N

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const SRC_URL =
  'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-no-swears.txt'
const __dirname = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(__dirname, '..', 'src', 'data', 'englishFrequency.js')

const args = process.argv.slice(2)
const topIdx = args.indexOf('--top')
const TOP = topIdx >= 0 ? parseInt(args[topIdx + 1], 10) : 2000
const localPath = args.find((a) => !a.startsWith('--') && a !== String(TOP))

async function loadSource() {
  if (localPath) return readFile(localPath, 'utf8')
  const res = await fetch(SRC_URL)
  if (!res.ok) throw new Error(`fetch ${SRC_URL} → HTTP ${res.status}`)
  return res.text()
}

const raw = await loadSource()
const seen = new Set()
const words = []
for (const line of raw.split('\n')) {
  const w = line.trim().toLowerCase()
  if (!/^[a-z][a-z'-]+$/.test(w)) continue // alphabetic, ≥ 2 chars, keep internal '/-
  if (seen.has(w)) continue
  seen.add(w)
  words.push(w)
  if (words.length >= TOP) break
}

if (words.length < TOP * 0.9) {
  throw new Error(`only ${words.length} words parsed (expected ~${TOP}) — source format changed?`)
}

const header = `// AUTO-GENERATED by scripts/build-english-frequency.mjs — DO NOT EDIT BY HAND.
//
// The ${words.length} most-common English words (by frequency rank). Used as the
// BASE "known word" set for the reader's dense-page easing on English (0510 ESL)
// docs — see src/lib/englishKnownWords.js. NEVER a translation authority.
//
// Source: first20hours/google-10000-english (Google Web Trillion Word Corpus).
// Code MIT; data permitted for educational/personal use — attribution + the
// commercial caveat are in public/CREDITS.txt. Alphabetic words ≥ 2 chars only,
// lowercased, deduped, frequency-rank order preserved; newline-delimited string
// for the smallest gzip footprint.
//
// Lazy-imported (src/lib/englishFrequency.js) so it never enters the main bundle.
`

const body = `const ENGLISH_FREQUENCY = ${JSON.stringify(words.join('\n'))}\n\nexport default ENGLISH_FREQUENCY\n`
await writeFile(OUT, `${header}\n${body}`, 'utf8')
console.log(`wrote ${OUT} — ${words.length} words (top ${TOP})`)
