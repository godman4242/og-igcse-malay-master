#!/usr/bin/env node
// Regenerates src/data/malayValidityList.js — the Tier-2 grounding VALIDITY asset.
//
// Source: iannho/Malay-Dataset · dictionary/Malays.dic.txt (a hunspell .dic of
// ~24.5k real Malay words, CC-BY 4.0 — see public/CREDITS.txt). We strip the
// hunspell affix flags (the "/ABC" suffix), drop the leading count line,
// lowercase, dedupe and sort, then emit a newline-delimited string (the smallest
// gzip footprint — far tighter than a JSON array of quoted words).
//
// The asset is used ONLY to label whether an AI-proposed Malay word is a *real*
// word; it is NEVER a translation authority (see the licensing decision doc
// docs/superpowers/specs/2026-06-06-for-you-phase2-dictionary-licensing.md).
//
// Usage:
//   node scripts/build-malay-validity.mjs                 # fetch the pinned URL
//   node scripts/build-malay-validity.mjs /path/Malays.dic # use a local file
//
// Network is needed only to REGENERATE (a maintainer task) — never at app
// build/runtime; the generated asset is committed and lazy-imported.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const SRC_URL =
  'https://raw.githubusercontent.com/iannho/Malay-Dataset/master/dictionary/Malays.dic.txt'
const __dirname = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(__dirname, '..', 'src', 'data', 'malayValidityList.js')

async function loadSource() {
  const arg = process.argv[2]
  if (arg) return readFile(arg, 'utf8')
  const res = await fetch(SRC_URL)
  if (!res.ok) throw new Error(`fetch ${SRC_URL} → HTTP ${res.status}`)
  return res.text()
}

const raw = await loadSource()
const lines = raw.split('\n')
// hunspell .dic starts with an entry-count line ("24550") — drop it.
if (/^\d+\s*$/.test(lines[0])) lines.shift()

const set = new Set()
for (const line of lines) {
  const word = line.split('/')[0].trim().toLowerCase() // strip "/AFFIXFLAGS"
  if (!word) continue
  // Defensive: never let a stray backtick/backslash/$ break the template literal.
  if (/[`\\$]/.test(word)) continue
  set.add(word)
}
const words = [...set].sort()

const header = `// AUTO-GENERATED by scripts/build-malay-validity.mjs — DO NOT EDIT BY HAND.
//
// Tier-2 grounding asset: ${words.length} real Malay words used ONLY as a VALIDITY
// signal in the AI deck confirm-flow ("is the proposed Malay word a real word?").
// It is NEVER a translation authority — see src/lib/malayValidity.js and the
// licensing decision docs/superpowers/specs/2026-06-06-for-you-phase2-dictionary-licensing.md.
//
// Source: iannho/Malay-Dataset · dictionary/Malays.dic.txt (hunspell; affix flags
// stripped, lowercased, deduped, sorted). Data licensed CC-BY 4.0 —
// https://github.com/iannho/Malay-Dataset · attribution: public/CREDITS.txt.
//
// Lazy-imported so it never enters the main bundle (loads only when a custom deck
// is generated). Newline-delimited for the smallest gzip footprint; split into a
// Set by buildValiditySet() in src/lib/malayValidity.js.`

const body = `export const MALAY_VALIDITY_WORDS = \`\n${words.join('\n')}\n\``

await writeFile(OUT, `${header}\n\n${body}\n`, 'utf8')
console.log(`wrote ${OUT} — ${words.length} words`)
